"""Generate the API reference pages from Crescent's own API description.

Reads `lua-api/docs/api.json` (members and their docs) and `lua-api/stubs/crescent/*.lua`
(constructors) from a Crescent checkout, and writes one page per class to
`docs/reference/<module>/<Class>.md` plus a module index. The pages are generated:
edit the Kotlin declarations in Crescent, re-export the API there, and run this again.

    python scripts/gen_reference.py [path/to/crescent]   (default: ../crescent)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
MODULE_TITLES = {"ui": "crescent.ui", "sys": "crescent.sys", "fs": "crescent.fs"}
GENERATED = "<!-- Generated by scripts/gen_reference.py from Crescent's lua-api. Do not edit. -->\n"


def constructors(stubs: Path) -> dict[str, list[str]]:
    """Class name -> its `fun(...)` overloads, from `---@overload fun(...): Name` lines."""
    found: dict[str, list[str]] = {}
    for f in stubs.glob("*.lua"):
        for m in re.finditer(r"^---@overload fun\((.*?)\): (\w+)$", f.read_text(encoding="utf-8"), re.M):
            found.setdefault(m.group(2), []).append(m.group(1))
    return found


def params(ps) -> str:
    out = []
    for p in ps:
        if isinstance(p, str):  # events list "name: type"
            out.append(p)
        else:
            out.append(f"{p['name']}{'?' if p.get('optional') else ''}: {p['type']}")
    return ", ".join(out)


def sentence(doc: str) -> str:
    doc = (doc or "").strip()
    return doc[:1].upper() + doc[1:] if doc else ""


def page(cls: dict, ctors: list[str]) -> str:
    module, name = cls["class"].split(".", 1)
    lines = [GENERATED, f"# {name}\n", f"`{MODULE_TITLES.get(module, module)}` · {sentence(cls['doc'])}\n"]
    req = f'local {module} = require("crescent.{module}")'
    if cls["kind"] == "class" and ctors:
        lines.append("## Create\n")
        lines.append("```lua")
        lines.append(req)
        for c in ctors:
            lines.append(f"{module}.{name}({c})")
        lines.append("```\n")
    by_kind: dict[str, list] = {}
    for m in cls["members"]:
        by_kind.setdefault(m["kind"], []).append(m)

    if by_kind.get("property"):
        lines.append("## Properties\n")
        lines.append("Each property has a getter and a setter: `getName()` / `setName(value)`; booleans also "
                     "read as `isName()`. Setters return the widget, so calls chain.\n")
        lines.append("| Property | Type | What it is |")
        lines.append("|---|---|---|")
        for m in sorted(by_kind["property"], key=lambda m: m["name"]):
            ro = " (read only)" if m.get("readOnly") else ""
            lines.append(f"| `{m['name']}` | `{m['type'].replace('|', ' or ')}` | {sentence(m['doc'])}{ro} |")
        lines.append("")
    for kind, title in (("method", "Methods"), ("function", "Functions"), ("event", "Events")):
        ms = by_kind.get(kind)
        if not ms:
            continue
        lines.append(f"## {title}\n")
        if kind == "event":
            lines.append("Every handler receives the widget first, then the values listed.\n")
        sep = "." if kind == "function" else ":"
        for m in sorted(ms, key=lambda m: m["name"]):
            sig = f"{name}{sep}{m['name']}({params(m.get('params', [])) if kind != 'event' else 'function(widget' + (', ' + params(m['params']) if m.get('params') else '') + ') end'})"
            lines.append(f"### `{m['name']}`\n")
            lines.append(f"```lua\n{sig}\n```\n")
            if m.get("doc"):
                lines.append(sentence(m["doc"]) + "\n")
    return "\n".join(lines)


def main() -> None:
    crescent = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "crescent").resolve()
    api = json.loads((crescent / "lua-api" / "docs" / "api.json").read_text(encoding="utf-8"))
    ctors = constructors(crescent / "lua-api" / "stubs" / "crescent")
    index: dict[str, list[tuple[str, str]]] = {}
    for cls in api:
        module, name = cls["class"].split(".", 1)
        target = OUT / module / f"{name}.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(page(cls, ctors.get(name, [])), encoding="utf-8")
        index.setdefault(module, []).append((name, sentence(cls["doc"])))
    for module, classes in index.items():
        rows = "\n".join(f"| [{n}]({n}.md) | {d} |" for n, d in sorted(classes))
        (OUT / module / "index.md").write_text(
            f"{GENERATED}\n# {MODULE_TITLES.get(module, module)}\n\n"
            f'```lua\nlocal {module} = require("crescent.{module}")\n```\n\n| Name | What it is |\n|---|---|\n{rows}\n',
            encoding="utf-8")
    write_nav(index)
    print(f"wrote {sum(len(v) for v in index.values())} pages from {crescent}")


def write_nav(index: dict[str, list[tuple[str, str]]]) -> None:
    """Rewrite the Reference section of zensical.toml's nav, between its two marker comments."""
    order = [m for m in ("ui", "sys", "fs") if m in index] + sorted(set(index) - {"ui", "sys", "fs"})
    lines = ['  { "Reference" = [']
    for module in order:
        lines.append(f'    {{ "{MODULE_TITLES.get(module, module)}" = [')
        lines.append(f'      "reference/{module}/index.md",')
        for name, _ in sorted(index[module]):
            lines.append(f'      {{ "{name}" = "reference/{module}/{name}.md" }},')
        lines.append("    ] },")
    lines.append("  ] },")
    toml = ROOT / "zensical.toml"
    text = toml.read_text(encoding="utf-8")
    start = text.index("# reference-nav:start")
    start = text.index("\n", start) + 1
    end = text.rindex("  # reference-nav:end")
    toml.write_text(text[:start] + "\n".join(lines) + "\n" + text[end:], encoding="utf-8")


if __name__ == "__main__":
    main()
